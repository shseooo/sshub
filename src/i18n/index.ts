const dicts: Record<Lang, Dict> = { ko, en, ja }

/** Default language follows the system locale; an explicit choice is persisted. */
export function detectLang(): Lang {
  const stored = localStorage.getItem('lang')
  if (stored === 'ko' || stored === 'en' || stored === 'ja') return stored
  const sys = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase()
  if (sys.startsWith('ko')) return 'ko'
  if (sys.startsWith('ja')) return 'ja'
  return 'en'
}

export function translate(
  lang: Lang,
  key: string,
  params?: Record<string, string | number>
): string {
  let s = dicts[lang][key] ?? en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}
